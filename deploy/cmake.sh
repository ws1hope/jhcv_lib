cmake -DCMAKE_BUILD_TYPE=Release \                          # Release 编译模式
-DCMAKE_INSTALL_PREFIX=/usr/local \                          # 安装路径
-DOPENCV_GENERATE_PKGCONFIG=ON \                             # 生成 pkg-config 配置
-DOPENCV_EXTRA_MODULES_PATH=/home/xfb/Downloads/opencv_contrib-master/modules \  # contrib 扩展模块路径
-DBUILD_DOCS=ON \                                            # 构建文档
-DBUILD_EXAMPLES=ON \                                        # 构建示例
-DINSTALL_C_EXAMPLES=ON \                                    # 安装 C 示例
-DWITH_QT=ON \                                                # 启用 Qt GUI 后端
-DWITH_GSTREAMER=ON \                                        # 启用 GStreamer
-DVIDEOIO_PLUGIN_LIST=gstreamer \                            # 视频 I/O 首选 GStreamer
-DOPENCV_ENABLE_NONFREE=ON \                                 # 启用非自由算法(SIFT/SURF)
-DBUILD_opencv_python2=OFF \                                 # 关闭 Python2 绑定
-DBUILD_opencv_python3=OFF \                                 # 关闭 Python3 绑定
-DWITH_LAPACK=ON \                                           # 启用 LAPACK 线性代数加速
-DWITH_EIGEN=ON \                                            # 启用 Eigen 矩阵运算
-DWITH_OPENGL=ON \                                           # 启用 OpenGL 3D 支持
-DWITH_CUDA=OFF \                                            # 关闭 CUDA (纯 CPU 编译)
-WITH_CUFFT=OFF \                                            # 关闭 CUDA FFT
-DWITH_CUBLAS=OFF \                                          # 关闭 CUDA BLAS
-DWITH_CUDNN=OFF \                                           # 关闭 cuDNN
-WITH_NVCUVID=OFF ..                                         # 关闭 NVIDIA 视频解码